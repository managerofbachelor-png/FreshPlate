export function getRecipeEstimatedCost(recipe: Recipe, country: CountryCode, servings?: number): number {
  const targetServings = servings ?? recipe.servings;
  const baseTotal = recipe.ingredients.reduce(
    (sum, ing) => sum + (country === 'BD' ? ing.bdCostPerBase : ing.usCostPerBase),
    0
  );
  const perServing = baseTotal / Math.max(1, recipe.servings);
  const scaled = perServing * targetServings;
  return country === 'BD' ? Math.round(scaled) : Number(scaled.toFixed(2));
}
